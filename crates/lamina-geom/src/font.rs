//! A single-stroke font for silkscreen and fab text. Each glyph is on a 4 x 6
//! grid (cap height 6, advance 5). The text size is the cap height in mm.

use lamina_model::{Point, Side};

type Stroke = &'static [(f32, f32)];

const O: Stroke = &[
    (1., 0.),
    (0., 1.),
    (0., 5.),
    (1., 6.),
    (3., 6.),
    (4., 5.),
    (4., 1.),
    (3., 0.),
    (1., 0.),
];
const P: Stroke = &[
    (0., 0.),
    (0., 6.),
    (3., 6.),
    (4., 5.),
    (4., 4.),
    (3., 3.),
    (0., 3.),
];
const DOT: Stroke = &[(2., 0.), (2., 0.35)];

fn glyph(c: char) -> &'static [Stroke] {
    match c.to_ascii_uppercase() {
        'A' => &[
            &[(0., 0.), (0., 4.), (2., 6.), (4., 4.), (4., 0.)],
            &[(0., 2.5), (4., 2.5)],
        ],
        'B' => &[
            &[
                (0., 0.),
                (0., 6.),
                (3., 6.),
                (4., 5.),
                (4., 4.),
                (3., 3.),
                (0., 3.),
            ],
            &[(3., 3.), (4., 2.), (4., 1.), (3., 0.), (0., 0.)],
        ],
        'C' => &[&[
            (4., 5.),
            (3., 6.),
            (1., 6.),
            (0., 5.),
            (0., 1.),
            (1., 0.),
            (3., 0.),
            (4., 1.),
        ]],
        'D' => &[&[
            (0., 0.),
            (0., 6.),
            (2.5, 6.),
            (4., 4.5),
            (4., 1.5),
            (2.5, 0.),
            (0., 0.),
        ]],
        'E' => &[
            &[(4., 6.), (0., 6.), (0., 0.), (4., 0.)],
            &[(0., 3.), (3., 3.)],
        ],
        'F' => &[&[(4., 6.), (0., 6.), (0., 0.)], &[(0., 3.), (3., 3.)]],
        'G' => &[&[
            (4., 5.),
            (3., 6.),
            (1., 6.),
            (0., 5.),
            (0., 1.),
            (1., 0.),
            (3., 0.),
            (4., 1.),
            (4., 3.),
            (2., 3.),
        ]],
        'H' => &[
            &[(0., 0.), (0., 6.)],
            &[(4., 0.), (4., 6.)],
            &[(0., 3.), (4., 3.)],
        ],
        'I' => &[
            &[(1., 6.), (3., 6.)],
            &[(2., 6.), (2., 0.)],
            &[(1., 0.), (3., 0.)],
        ],
        'J' => &[&[(4., 6.), (4., 1.), (3., 0.), (1., 0.), (0., 1.)]],
        'K' => &[
            &[(0., 0.), (0., 6.)],
            &[(4., 6.), (0., 2.)],
            &[(1.2, 3.2), (4., 0.)],
        ],
        'L' => &[&[(0., 6.), (0., 0.), (4., 0.)]],
        'M' => &[&[(0., 0.), (0., 6.), (2., 3.), (4., 6.), (4., 0.)]],
        'N' => &[&[(0., 0.), (0., 6.), (4., 0.), (4., 6.)]],
        'O' => &[O],
        'P' => &[P],
        'Q' => &[O, &[(2.5, 1.5), (4., 0.)]],
        'R' => &[P, &[(2., 3.), (4., 0.)]],
        'S' => &[&[
            (4., 5.),
            (3., 6.),
            (1., 6.),
            (0., 5.),
            (0., 4.),
            (1., 3.),
            (3., 3.),
            (4., 2.),
            (4., 1.),
            (3., 0.),
            (1., 0.),
            (0., 1.),
        ]],
        'T' => &[&[(0., 6.), (4., 6.)], &[(2., 6.), (2., 0.)]],
        'U' => &[&[(0., 6.), (0., 1.), (1., 0.), (3., 0.), (4., 1.), (4., 6.)]],
        'V' => &[&[(0., 6.), (2., 0.), (4., 6.)]],
        'W' => &[&[(0., 6.), (1., 0.), (2., 3.), (3., 0.), (4., 6.)]],
        'X' => &[&[(0., 0.), (4., 6.)], &[(0., 6.), (4., 0.)]],
        'Y' => &[&[(0., 6.), (2., 3.), (4., 6.)], &[(2., 3.), (2., 0.)]],
        'Z' => &[&[(0., 6.), (4., 6.), (0., 0.), (4., 0.)]],
        '0' => &[O, &[(1., 1.5), (3., 4.5)]],
        '1' => &[&[(1., 5.), (2., 6.), (2., 0.)], &[(1., 0.), (3., 0.)]],
        '2' => &[&[
            (0., 5.),
            (1., 6.),
            (3., 6.),
            (4., 5.),
            (4., 4.),
            (0., 0.),
            (4., 0.),
        ]],
        '3' => &[
            &[
                (0., 5.),
                (1., 6.),
                (3., 6.),
                (4., 5.),
                (4., 4.),
                (3., 3.),
                (4., 2.),
                (4., 1.),
                (3., 0.),
                (1., 0.),
                (0., 1.),
            ],
            &[(1.5, 3.), (3., 3.)],
        ],
        '4' => &[&[(3., 0.), (3., 6.), (0., 2.), (4., 2.)]],
        '5' => &[&[
            (4., 6.),
            (0., 6.),
            (0., 3.),
            (3., 3.),
            (4., 2.),
            (4., 1.),
            (3., 0.),
            (1., 0.),
            (0., 1.),
        ]],
        '6' => &[&[
            (3., 6.),
            (1., 6.),
            (0., 5.),
            (0., 1.),
            (1., 0.),
            (3., 0.),
            (4., 1.),
            (4., 2.),
            (3., 3.),
            (0., 3.),
        ]],
        '7' => &[&[(0., 6.), (4., 6.), (1., 0.)]],
        '8' => &[&[
            (1., 3.),
            (0., 4.),
            (0., 5.),
            (1., 6.),
            (3., 6.),
            (4., 5.),
            (4., 4.),
            (3., 3.),
            (1., 3.),
            (0., 2.),
            (0., 1.),
            (1., 0.),
            (3., 0.),
            (4., 1.),
            (4., 2.),
            (3., 3.),
        ]],
        '9' => &[&[
            (1., 0.),
            (3., 0.),
            (4., 1.),
            (4., 5.),
            (3., 6.),
            (1., 6.),
            (0., 5.),
            (0., 4.),
            (1., 3.),
            (4., 3.),
        ]],
        '-' => &[&[(1., 3.), (3., 3.)]],
        '+' => &[&[(0., 3.), (4., 3.)], &[(2., 1.), (2., 5.)]],
        '.' => &[DOT],
        ',' => &[&[(2., 0.4), (1.5, -1.)]],
        ':' => &[&[(2., 1.), (2., 1.35)], &[(2., 4.), (2., 4.35)]],
        '/' => &[&[(0., 0.), (4., 6.)]],
        '\\' => &[&[(0., 6.), (4., 0.)]],
        '_' => &[&[(0., 0.), (4., 0.)]],
        '(' => &[&[(3., 6.), (1.5, 4.5), (1.5, 1.5), (3., 0.)]],
        ')' => &[&[(1., 6.), (2.5, 4.5), (2.5, 1.5), (1., 0.)]],
        '[' => &[&[(3., 6.), (1.5, 6.), (1.5, 0.), (3., 0.)]],
        ']' => &[&[(1., 6.), (2.5, 6.), (2.5, 0.), (1., 0.)]],
        '=' => &[&[(0., 2.), (4., 2.)], &[(0., 4.), (4., 4.)]],
        '#' => &[
            &[(1., 0.), (1., 6.)],
            &[(3., 0.), (3., 6.)],
            &[(0., 2.), (4., 2.)],
            &[(0., 4.), (4., 4.)],
        ],
        '%' => &[
            &[(0., 0.), (4., 6.)],
            &[(0., 6.), (1., 6.), (1., 5.), (0., 5.), (0., 6.)],
            &[(3., 1.), (4., 1.), (4., 0.), (3., 0.), (3., 1.)],
        ],
        '!' => &[&[(2., 6.), (2., 2.)], DOT],
        '\'' => &[&[(2., 6.), (2., 4.5)]],
        '"' => &[&[(1., 6.), (1., 4.5)], &[(3., 6.), (3., 4.5)]],
        '<' => &[&[(4., 5.), (0., 3.), (4., 1.)]],
        '>' => &[&[(0., 5.), (4., 3.), (0., 1.)]],
        '*' => &[
            &[(2., 1.), (2., 5.)],
            &[(0., 2.), (4., 4.)],
            &[(0., 4.), (4., 2.)],
        ],
        '~' => &[&[(0., 3.), (1., 4.), (3., 2.), (4., 3.)]],
        '&' => &[&[
            (4., 0.),
            (1., 4.),
            (1., 5.),
            (2., 6.),
            (3., 5.),
            (3., 4.),
            (0., 2.),
            (0., 1.),
            (1., 0.),
            (2., 0.),
            (4., 2.),
        ]],
        ' ' => &[],
        _ => &[&[(0., 0.), (4., 0.), (4., 6.), (0., 6.), (0., 0.)]],
    }
}

/// Return the stroke polylines for `text`, with the centre at `at` and a
/// rotation of `rotation` degrees. `size` is the cap height in mm.
pub fn text_strokes(text: &str, at: Point, size: f64, rotation: f64) -> Vec<Vec<Point>> {
    let s = size / 6.0;
    let n = text.chars().count();
    if n == 0 {
        return Vec::new();
    }
    let width = (n as f64 * 5.0 - 1.0) * s;
    let x0 = -width / 2.0;
    let y0 = -3.0 * s;
    let mut out = Vec::new();
    for (i, c) in text.chars().enumerate() {
        let ox = x0 + i as f64 * 5.0 * s;
        for stroke in glyph(c) {
            let pts: Vec<Point> = stroke
                .iter()
                .map(|(x, y)| {
                    Point::new(ox + *x as f64 * s, y0 + *y as f64 * s)
                        .rotated(rotation)
                        .add(at)
                })
                .collect();
            out.push(pts);
        }
    }
    out
}

/// The strokes of `text` as the board shows it. On the bottom side, the text is
/// mirrored about its anchor.
pub fn side_text_strokes(
    text: &str,
    at: Point,
    size: f64,
    rotation: f64,
    side: Side,
) -> Vec<Vec<Point>> {
    if side == Side::Top {
        return text_strokes(text, at, size, rotation);
    }
    text_strokes(text, at, size, -rotation)
        .into_iter()
        .map(|s| {
            s.into_iter()
                .map(|p| Point::new(2.0 * at.x - p.x, p.y))
                .collect()
        })
        .collect()
}

/// The rotation of a part text on the board. If the placement turns the text
/// upside down, turn it 180 degrees.
pub fn upright(rotation: f64) -> f64 {
    let norm = rotation.rem_euclid(360.0);
    if norm > 90.0 && norm <= 270.0 {
        rotation + 180.0
    } else {
        rotation
    }
}

/// The stroke width of silkscreen text.
pub fn silk_stroke_width(size: f64, silk_width: f64) -> f64 {
    silk_width.max(size * 0.15)
}

/// Width of `text` at `size` in mm.
pub fn text_width(text: &str, size: f64) -> f64 {
    let n = text.chars().count() as f64;
    ((n * 5.0 - 1.0) * size / 6.0).max(0.0)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn centred() {
        let s = text_strokes("HE", Point::new(10.0, 5.0), 1.2, 0.0);
        let xs: Vec<f64> = s.iter().flatten().map(|p| p.x).collect();
        let lo = xs.iter().cloned().fold(f64::INFINITY, f64::min);
        let hi = xs.iter().cloned().fold(f64::NEG_INFINITY, f64::max);
        assert!(((lo + hi) / 2.0 - 10.0).abs() < 1e-9);
        assert!((text_width("HE", 1.2) - (hi - lo)).abs() < 1e-9);
    }

    #[test]
    fn every_printable_char_has_strokes() {
        for c in '!'..='~' {
            assert!(!glyph(c).is_empty(), "{c}");
        }
    }
}
